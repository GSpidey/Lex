import { readFile, readdir, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const directory = path.join(root, 'docs/legal');
const quote = (value) => `'${value.replaceAll("'", "''")}'`;
const aliases = { 'emergency-disclaimer': 'emergency-outcomes', subprocessors: 'cross-border-subprocessors' };
const statements = ['-- Generated by scripts/build-legal-migration.mjs; immutable review drafts, never auto-published.'];
for (const file of (await readdir(directory)).filter((name) => name.endsWith('.md')).sort()) {
  const source = await readFile(path.join(directory, file), 'utf8');
  const content = source.replaceAll('\r\n', '\n');
  const code = aliases[file.slice(0, -3)] ?? file.slice(0, -3);
  const title = content.split('\n')[0].replace(/^# /, '');
  const unresolved = [...new Set([...content.matchAll(/\[([A-Z][A-Z0-9_]+)\]/g)].map((m) => m[1]))];
  const digest = createHash('sha256').update(content).digest('base64');
  const privateDocument = code === 'intercompany-services';
  const id = `legal-${code}`;
  statements.push(`INSERT OR IGNORE INTO legal_documents (id,code,title,audience,optional,visibility,acceptance_kind,created_at,updated_at) VALUES (${quote(id)},${quote(code)},${quote(title)},${quote(privateDocument ? 'owner' : 'all')},0,${quote(privateDocument ? 'owners' : 'public')},'notice','2026-10-13T00:00:00.000Z','2026-10-13T00:00:00.000Z');`);
  statements.push(`INSERT INTO legal_document_versions (id,document_id,version,language,status,content_markdown,company_placeholder_present,content_hash,unresolved_fields_json,created_at,updated_at) SELECT ${quote(`${code}-en-v2`)},id,2,'en','draft',${quote(content)},${unresolved.length ? 1 : 0},${quote(digest)},${quote(JSON.stringify(unresolved))},'2026-10-13T00:00:00.000Z','2026-10-13T00:00:00.000Z' FROM legal_documents WHERE code=${quote(code)};`);
}
statements.push("UPDATE legal_documents SET acceptance_kind='notice' WHERE code IN ('emergency-outcomes','cross-border-subprocessors');");
const output = path.join(root, 'apps/cloudflare-api/migrations/0006_substantive_legal_drafts.sql');
await writeFile(output, `${statements.join('\n\n')}\n`);
console.log(`Compiled ${statements.length - 2} statements into a review-only migration.`);
